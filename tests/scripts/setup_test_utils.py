"""Load the production setup module for build-contract tests."""

import importlib.util
from pathlib import Path
from types import ModuleType


def load_setup_module() -> ModuleType:
    setup_path = Path(__file__).resolve().parents[2] / "setup.py"
    spec = importlib.util.spec_from_file_location("xllm_setup", setup_path)
    assert spec is not None
    assert spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module
